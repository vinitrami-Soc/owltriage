"""Weekly rule watch: what changed out there that OwlTriage's rules should know about.

Run by the `Rule watch` GitHub workflow every Monday (or by hand):

    python tools/rule_watch.py --kev kev.json --nuclei-index cves.json --attack enterprise-attack.json \\
        --benign access.log --previous previous-issues.txt --issue issue.md --pr pr.md

Reports, for a person to decide (issue.md):
  * CISA Known Exploited Vulnerabilities added in the last 30 days and not reported before, with known
    ransomware use and whether a public web exploit template (nuclei) exists.
  * ATT&CK techniques in owltriage/resources/attack.yml that MITRE revoked or deprecated, with the
    replacement and the rules that use them.
Proposes, for a pull request (written to the repo, explained in pr.md):
  * A web rule per new KEV CVE whose nuclei template requests a distinctive path, in
    owltriage/rules/web-kev.yml. A rule must pass its own examples and match nothing in a benign
    access log, or it is left out (and the issue says why).
  * ATT&CK names MITRE changed, in owltriage/resources/attack.yml.
  * A new owltriage/rules/VERSION when rules changed, so the merged pull request becomes a rules pack.

Each reported item carries a hidden marker (<!-- kev:CVE-... -->), so it is never reported twice.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from dataclasses import dataclass, field
from datetime import date, datetime, timedelta, timezone
from pathlib import Path
from typing import Dict, List, Optional, Set

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from owltriage.log_parser import parse_line  # noqa: E402
from owltriage.rules import (RuleError, load_rules, packaged_rule_texts, rules_digest, run_rule_tests,  # noqa: E402
                             version_key)
from owltriage.utils import clean  # noqa: E402

NUCLEI_RAW = "https://raw.githubusercontent.com/projectdiscovery/nuclei-templates/main/"
NUCLEI_WEB = "https://github.com/projectdiscovery/nuclei-templates/blob/main/"
WINDOW_DAYS = 30
MAX_NEW_RULES = 20
MAX_ISSUE_ROWS = 100        # the rest waits for next week (they keep no marker yet)
GENERATED_FILE = "web-kev.yml"
GENERATED_HEADER = (
    "# Generated by tools/rule_watch.py from CISA's Known Exploited Vulnerabilities and public nuclei\n"
    "# templates, and reviewed in a pull request before merging. Each rule fires on a request to the\n"
    "# endpoint a known-exploited CVE is attacked through. Edit freely; the watch only appends.\n\n")
KEV_MARK = re.compile(r"<!-- kev:(CVE-\d{4}-\d{4,7}) -->")
ATTACK_MARK = re.compile(r"<!-- attack:(T\d{4}(?:\.\d{3})?):([a-z]+) -->")
RAW_REQUEST = re.compile(r"^[A-Z]+\s+(\S+)\s+HTTP/")
ATTACK_LINE = re.compile(r"^(T\d{4}(?:\.\d{3})?):\s*\{.*\}\s*$")
# Requests every visitor of a site makes: never evidence of an exploit on their own.
GENERIC_SEGMENTS = {"", "api", "v1", "v2", "v3", "v4", "rest", "admin", "login", "logout", "login.php", "index.php",
                    "index.html", "index.htm", "index.jsp", "default.aspx", "home", "user", "users", "sign_in",
                    "signin", "auth", "oauth", "graphql", "version", "status", "health", "console", "dashboard",
                    "wp-login.php", "xmlrpc.php", "robots.txt", "favicon.ico", "static", "assets", "js", "css",
                    "me", "self", "profile", "account", "accounts", "session", "sessions", "settings", "config",
                    "search", "upload", "uploads", "download", "file", "files", "info", "data", "public", "app",
                    "apps", "web", "rpc", "json", "service", "services", "default", "portal", "ui", "cgi-bin"}
VERSION_SEGMENT = re.compile(r"^v\d+(?:\.\d+)*$", re.IGNORECASE)
MIN_SPECIFIC_CHARS = 8


# -- CISA KEV ---------------------------------------------------------------------------------------
@dataclass
class KevEntry:
    cve: str
    vendor: str
    product: str
    name: str
    added: date
    ransomware: str
    forensic: str


def load_kev(data: dict) -> List[KevEntry]:
    entries = []
    for item in data.get("vulnerabilities", []):
        try:
            added = date.fromisoformat(str(item["dateAdded"])[:10])
        except (KeyError, ValueError):
            continue
        entries.append(KevEntry(str(item.get("cveID", "")), clean(item.get("vendorProject", ""), 60),
                                clean(item.get("product", ""), 60), clean(item.get("vulnerabilityName", ""), 150),
                                added, str(item.get("knownRansomwareCampaignUse", "Unknown")),
                                str(item.get("forensicTriage", ""))))
    return entries


def reported(previous: str) -> Dict[str, Set[str]]:
    """What earlier issues already reported, from their hidden markers."""
    return {"kev": set(KEV_MARK.findall(previous)),
            "attack": {f"{tid}:{kind}" for tid, kind in ATTACK_MARK.findall(previous)}}


def new_kev(entries: List[KevEntry], seen: Set[str], today: date, window_days: int = WINDOW_DAYS) -> List[KevEntry]:
    start = today - timedelta(days=window_days)
    fresh = [e for e in entries if e.cve not in seen and start <= e.added <= today]
    return sorted(fresh, key=lambda e: (e.added, e.cve), reverse=True)


# -- nuclei templates -------------------------------------------------------------------------------
def nuclei_index(text: str) -> Dict[str, str]:
    """CVE id -> template path, for HTTP templates only (the only ones a web log can show)."""
    index = {}
    for line in text.splitlines():
        if not line.strip():
            continue
        item = json.loads(line)
        if str(item.get("file_path", "")).startswith("http/"):
            index[item["ID"]] = item["file_path"]
    return index


def _static(path: str) -> str:
    path = path.split("{{", 1)[0]            # the rest is filled in at scan time
    return path if path.startswith("/") else "/" + path


def request_paths(template: str) -> List[str]:
    """The static part of every request path in a nuclei template, in order, without duplicates."""
    try:
        data = yaml.safe_load(template) or {}
    except yaml.YAMLError:
        return []
    if not isinstance(data, dict):
        return []
    blocks = data.get("http") or data.get("requests") or []
    paths: List[str] = []
    for block in blocks if isinstance(blocks, list) else []:
        if not isinstance(block, dict):
            continue
        for value in block.get("path") or []:
            for prefix in ("{{BaseURL}}", "{{RootURL}}"):
                if isinstance(value, str) and value.startswith(prefix):
                    paths.append(_static(value[len(prefix):]))
        for raw in block.get("raw") or []:
            lines = [ln.strip() for ln in str(raw).splitlines() if ln.strip() and not ln.strip().startswith("@")]
            match = RAW_REQUEST.match(lines[0]) if lines else None
            if match:
                paths.append(_static(match.group(1)))
    return list(dict.fromkeys(paths))


def _base(path: str) -> str:
    return path.split("?", 1)[0].rstrip("/") or "/"


def distinctive(path: str) -> bool:
    """A path only this product's exploit would request, not one every visitor of a site requests."""
    base = _base(path)
    segments = [s for s in base.split("/") if s]
    specific = [s for s in segments if s.lower() not in GENERIC_SEGMENTS and not VERSION_SEGMENT.match(s)]
    if len(base) < 10 or sum(len(s) for s in specific) < MIN_SPECIFIC_CHARS:   # e.g. /v1/users/me, /api/v4/ci/lint
        return False
    return len(segments) >= 2 or "." in segments[-1]


def candidate_rule(entry: KevEntry, template: str, template_path: str) -> Optional[dict]:
    bases = list(dict.fromkeys(_base(p) for p in request_paths(template) if distinctive(p)))[:3]
    if not bases:
        return None
    shortest = min(bases, key=len)
    benign = shortest.rsplit("/", 1)[0] + "/"
    product = f"{entry.vendor} {entry.product}".strip()
    return {
        "id": f"web-{entry.cve.lower()}",
        "name": "KNOWN_EXPLOITED_CVE",
        "title": clean(f"{entry.cve} exploit path ({product})", 100),
        "type": "web",
        "severity": "high" if entry.ransomware == "Known" else "medium",   # a path alone proves a probe, not a hit
        "mitre": ["T1190"],
        "pattern": "|".join(re.escape(b) for b in bases),
        "description": (f"CISA KEV, added {entry.added}: {entry.name}. A request to this endpoint is how the exploit "
                        f"starts. On a server that runs {product}, check the status code and the source before acting."),
        "false_positives": [f"Normal use of {product} on servers that run it"],
        "references": [f"https://nvd.nist.gov/vuln/detail/{entry.cve}", NUCLEI_WEB + template_path],
        "author": "rule-watch (from a public nuclei template; reviewed in a pull request)",
        "tests": {"match": bases, "no_match": [benign]},
    }


# -- ATT&CK -------------------------------------------------------------------------------------------
@dataclass
class AttackChange:
    tid: str
    kind: str                 # renamed | revoked | deprecated | missing
    old_name: str
    new_name: str = ""
    replacement: str = ""
    used_by: List[str] = field(default_factory=list)


def attack_changes(bundle: dict, ours: Dict[str, dict], usage: Dict[str, List[str]]) -> List[AttackChange]:
    objects = bundle.get("objects", [])
    by_ext: Dict[str, dict] = {}
    for obj in objects:
        if obj.get("type") != "attack-pattern":
            continue
        for ref in obj.get("external_references", []):
            if ref.get("source_name") == "mitre-attack" and ref.get("external_id"):
                by_ext.setdefault(ref["external_id"], obj)
    ext_of = {obj["id"]: tid for tid, obj in by_ext.items()}
    revoked_by = {rel["source_ref"]: rel["target_ref"] for rel in objects
                  if rel.get("type") == "relationship" and rel.get("relationship_type") == "revoked-by"}

    def full_name(tid: str) -> Optional[str]:
        obj = by_ext[tid]
        if "." not in tid:
            return obj["name"]
        parent = by_ext.get(tid.split(".", 1)[0])
        return f"{parent['name']}: {obj['name']}" if parent else None

    changes = []
    for tid in sorted(ours):
        old = str((ours[tid] or {}).get("name", ""))
        used = sorted(usage.get(tid, []))
        obj = by_ext.get(tid)
        if obj is None:
            changes.append(AttackChange(tid, "missing", old, used_by=used))
        elif obj.get("revoked"):
            replacement = ext_of.get(revoked_by.get(obj["id"], ""), "")
            new = (full_name(replacement) or "") if replacement else ""
            changes.append(AttackChange(tid, "revoked", old, new, replacement, used))
        elif obj.get("x_mitre_deprecated"):
            changes.append(AttackChange(tid, "deprecated", old, used_by=used))
        else:
            new = full_name(tid)
            if new and new != old:
                changes.append(AttackChange(tid, "renamed", old, new, used_by=used))
    return changes


def _yaml_str(text: str) -> str:
    return json.dumps(text) if re.search(r"[:,{}\[\]#&*!|>'\"%@`]", text) or text != text.strip() else text


def rename_techniques(text: str, renames: Dict[str, str]) -> str:
    """Change only the names in attack.yml, keeping comments, order and tactics."""
    out = []
    for line in text.splitlines(keepends=True):
        match = ATTACK_LINE.match(line.rstrip("\r\n"))
        if match and match.group(1) in renames:
            tid = match.group(1)
            tactics = ", ".join((yaml.safe_load(line)[tid] or {}).get("tactics", []))
            out.append(f"{tid}: {{name: {_yaml_str(renames[tid])}, tactics: [{tactics}]}}\n")
        else:
            out.append(line)
    return "".join(out)


# -- versions ------------------------------------------------------------------------------------------
def bump_version(current: str, today: date) -> str:
    """Today's date, or a counter on top of the current version when that is today (or later)."""
    base = today.strftime("%Y.%m.%d")
    if version_key(base) > version_key(current):
        return base
    parts = current.split(".")
    if len(parts) == 4:
        return ".".join(parts[:3] + [str(int(parts[3]) + 1)])
    return f"{current}.2" if current == base else f"{current}.1"


def write_version(rules_dir: Path, version: str) -> None:
    path = rules_dir / "VERSION"
    digest = rules_digest(packaged_rule_texts(rules_dir))
    text = re.sub(r"(?m)^version:.*$", f"version: {version}", path.read_text(encoding="utf-8"))
    path.write_text(re.sub(r"(?m)^digest:.*$", f"digest: {digest}", text), encoding="utf-8")


# -- the run -----------------------------------------------------------------------------------------
def benign_paths(text: str) -> List[str]:
    paths = []
    for line in text.splitlines():
        event = parse_line(line)
        if event.kind == "http_request" and event.path:
            paths.append(event.path)
    return paths


def fetch_template(path: str, templates_dir: Optional[Path], cve: str) -> Optional[str]:
    if templates_dir is not None:
        local = templates_dir / f"{cve}.yaml"
        return local.read_text(encoding="utf-8") if local.is_file() else None
    import requests
    try:
        response = requests.get(NUCLEI_RAW + path, timeout=30)
        response.raise_for_status()
        return response.text[:500_000]
    except requests.RequestException:
        return None


@dataclass
class KevRow:
    entry: KevEntry
    template: str = ""                    # template path, if any
    rule: str = ""                        # proposed rule id
    note: str = ""                        # why there is no rule


def run(args) -> int:
    repo = Path(args.repo)
    rules_dir, attack_file = repo / "owltriage" / "rules", repo / "owltriage" / "resources" / "attack.yml"
    today = date.fromisoformat(args.today) if args.today else datetime.now(timezone.utc).date()
    previous = Path(args.previous).read_text(encoding="utf-8") if args.previous and Path(args.previous).is_file() else ""
    seen = reported(previous)
    current_rules = load_rules(packaged_dir=rules_dir)

    # 1. new KEV entries, and candidate rules for the ones with a distinctive exploit path
    index = nuclei_index(Path(args.nuclei_index).read_text(encoding="utf-8"))
    rows: List[KevRow] = []
    candidates: List[dict] = []
    fresh = new_kev(load_kev(json.loads(Path(args.kev).read_text(encoding="utf-8"))), seen["kev"], today)
    for entry in fresh[:MAX_ISSUE_ROWS]:
        row = KevRow(entry, index.get(entry.cve, ""))
        rows.append(row)
        rule_id = f"web-{entry.cve.lower()}"
        if not row.template:
            row.note = "no public web exploit template"
        elif rule_id in current_rules.rules:
            row.rule, row.note = rule_id, "rule already exists"
        elif len(candidates) >= MAX_NEW_RULES:
            row.note = "over this week's limit; next run"
        else:
            text = fetch_template(row.template, Path(args.templates_dir) if args.templates_dir else None, entry.cve)
            rule = candidate_rule(entry, text, row.template) if text else None
            if text is None:
                row.note = "template could not be downloaded"
            elif rule is None:
                row.note = "template requests no distinctive path"
            else:
                candidates.append(rule)
                row.rule = rule["id"]

    # 2. keep only candidates that pass their own examples and stay quiet on normal traffic
    benign = benign_paths(Path(args.benign).read_text(encoding="utf-8", errors="replace")) if args.benign else []
    generated_path = rules_dir / GENERATED_FILE
    existing = yaml.safe_load(generated_path.read_text(encoding="utf-8")) if generated_path.is_file() else []
    skipped: Dict[str, str] = {}
    if candidates:
        texts = dict(packaged_rule_texts(rules_dir))
        texts[GENERATED_FILE] = yaml.safe_dump((existing or []) + candidates, sort_keys=False)
        try:
            trial = load_rules(packaged_texts=texts)
        except RuleError as exc:
            trial, skipped = None, {c["id"]: f"does not load ({clean(exc, 100)})" for c in candidates}
        if trial is not None:
            failed = {r.rule.id: r.failures[0] for r in run_rule_tests(trial, [c["id"] for c in candidates]) if not r.ok}
            for candidate in candidates:
                rule = trial.rules[candidate["id"]]
                hit = next((p for p in benign if rule.search_web(p)), None)
                if candidate["id"] in failed:
                    skipped[candidate["id"]] = f"fails its own examples ({failed[candidate['id']]})"
                elif hit is not None:
                    skipped[candidate["id"]] = f"matches normal traffic (`{clean(hit, 80)}`)"
    accepted = [c for c in candidates if c["id"] not in skipped]
    for row in rows:
        if row.rule in skipped:
            row.note, row.rule = f"not proposed: {skipped[row.rule]}", ""

    # 3. ATT&CK: rename in the PR, everything else for a person
    ours = yaml.safe_load(attack_file.read_text(encoding="utf-8")) or {}
    usage: Dict[str, List[str]] = {}
    for rule in current_rules.rules.values():
        for tid in rule.mitre:
            usage.setdefault(tid, []).append(rule.id)
    changes = [c for c in attack_changes(json.loads(Path(args.attack).read_text(encoding="utf-8")), ours, usage)
               if f"{c.tid}:{c.kind}" not in seen["attack"]]
    renames = {c.tid: c.new_name for c in changes if c.kind == "renamed"}

    # 4. write the proposal
    if accepted:
        all_rules = sorted((existing or []) + accepted, key=lambda r: r["id"])
        generated_path.write_text(GENERATED_HEADER + yaml.safe_dump(all_rules, sort_keys=False, allow_unicode=True,
                                                                    width=110), encoding="utf-8")
    if renames:
        attack_file.write_text(rename_techniques(attack_file.read_text(encoding="utf-8"), renames), encoding="utf-8")
    version = ""
    if accepted:
        version = bump_version(current_version(rules_dir), today)
        write_version(rules_dir, version)

    Path(args.issue).write_text(issue_text(today, rows, changes, accepted), encoding="utf-8")
    Path(args.pr).write_text(pr_text(accepted, rows, renames, version), encoding="utf-8")
    print(f"report={'true' if rows or changes else 'false'}")
    print(f"changes={'true' if accepted or renames else 'false'}")
    return 0


def current_version(rules_dir: Path) -> str:
    match = re.search(r"(?m)^version:\s*(\S+)", (rules_dir / "VERSION").read_text(encoding="utf-8"))
    return match.group(1) if match else "0000.00.00"


def issue_text(today: date, rows: List[KevRow], changes: List[AttackChange], accepted: List[dict]) -> str:
    out = [f"Weekly rule watch for {today}: {len(rows)} new known-exploited CVE(s), "
           f"{len(changes)} ATT&CK change(s), {len(accepted)} candidate rule(s).", ""]
    if rows:
        out += ["### New in CISA's Known Exploited Vulnerabilities", "",
                "| CVE | Vulnerability | Added | Ransomware | Web exploit template | Rule |", "|---|---|---|---|---|---|"]
        for row in rows:
            e = row.entry
            template = f"[yes]({NUCLEI_WEB}{row.template})" if row.template else "no"
            rule = f"`{row.rule}` proposed" if row.rule and not row.note else (row.note or "-")
            ransomware = "**Known**" if e.ransomware == "Known" else e.ransomware
            out.append(f"| [{e.cve}](https://nvd.nist.gov/vuln/detail/{e.cve}) | {e.name or e.vendor + ' ' + e.product} | "
                       f"{e.added} | {ransomware} | {template} | {rule} |")
        out += ["", "Rows without a rule need a person: would this attack show in the logs OwlTriage reads (Linux auth, "
                "web access logs, Windows events)? If so, write a rule (docs/RULES.md)."]
    if changes:
        out += ["", "### ATT&CK changes", ""]
        for c in changes:
            users = f" Used by: {', '.join(f'`{u}`' for u in c.used_by)}." if c.used_by else ""
            if c.kind == "renamed":
                out.append(f"- **{c.tid}** was renamed to \"{c.new_name}\". Fixed in the pull request.{users}")
            elif c.kind == "revoked":
                instead = f" MITRE now uses **{c.replacement}** ({c.new_name})." if c.replacement else ""
                out.append(f"- **{c.tid}** ({c.old_name}) was **revoked**.{instead}{users} Update the rules' `mitre:` "
                           "lists, owltriage/resources/attack.yml and any tests that expect the old ID.")
            elif c.kind == "deprecated":
                out.append(f"- **{c.tid}** ({c.old_name}) is **deprecated** with no replacement.{users} "
                           "Map the rules to the closest current technique.")
            else:
                out.append(f"- **{c.tid}** ({c.old_name}) is not in ATT&CK any more.{users}")
    out.append("")
    out += [f"<!-- kev:{row.entry.cve} -->" for row in rows]
    out += [f"<!-- attack:{c.tid}:{c.kind} -->" for c in changes]
    return "\n".join(out) + "\n"


def pr_text(accepted: List[dict], rows: List[KevRow], renames: Dict[str, str], version: str) -> str:
    out = ["Proposed by the weekly rule watch. Nothing reaches users until this is merged; merging publishes a "
           f"new signed rules pack{f' ({version})' if version else ''}.", ""]
    if accepted:
        out += [f"### Candidate rules in `owltriage/rules/{GENERATED_FILE}`", "",
                "| Rule | Severity | Fires on requests to | Source |", "|---|---|---|---|"]
        for rule in accepted:
            paths = ", ".join(f"`{p}`" for p in rule["tests"]["match"])
            out.append(f"| `{rule['id']}` {rule['title']} | {rule['severity']} | {paths} | "
                       f"[nuclei template]({rule['references'][1]}) |")
        out.append("")
    left_out = [r for r in rows if r.note.startswith("not proposed")]
    if left_out:
        out += ["Left out automatically:", ""]
        out += [f"- {r.entry.cve}: {r.note[len('not proposed: '):]}" for r in left_out]
        out.append("")
    if renames:
        out += ["### ATT&CK names MITRE changed", ""]
        out += [f"- {tid}: \"{name}\"" for tid, name in sorted(renames.items())]
        out.append("")
    out += ["### Before merging", "",
            "- [ ] Each path is the endpoint the exploit uses, not a page or API that normal use of the product calls "
            "(if it is, narrow the pattern or drop the rule).",
            "- [ ] The severity fits: `high` means the CVE is known to be used by ransomware, `medium` otherwise.",
            "- [ ] Every rule passed its own examples and matched nothing in a benign access log (checked by the run).",
            ""]
    return "\n".join(out)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(prog="rule_watch.py", description=__doc__.splitlines()[0])
    parser.add_argument("--repo", default=str(ROOT), help="repository root to update (default: this one)")
    parser.add_argument("--kev", required=True, help="CISA known_exploited_vulnerabilities.json")
    parser.add_argument("--nuclei-index", required=True, help="nuclei-templates cves.json")
    parser.add_argument("--attack", required=True, help="MITRE enterprise-attack.json (STIX bundle)")
    parser.add_argument("--benign", help="a normal web access log; rules that match it are left out")
    parser.add_argument("--previous", help="text of earlier rule-watch issues (their markers prevent repeats)")
    parser.add_argument("--templates-dir", help="read nuclei templates from here (CVE-...yaml) instead of GitHub")
    parser.add_argument("--today", help="YYYY-MM-DD (default: today, UTC)")
    parser.add_argument("--issue", required=True, help="where to write the issue text")
    parser.add_argument("--pr", required=True, help="where to write the pull request text")
    return run(parser.parse_args(argv))


if __name__ == "__main__":
    sys.exit(main())
