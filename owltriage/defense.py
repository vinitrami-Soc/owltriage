"""Option 1, Phase 4: active defense (local).

Builds iptables / ip6tables commands for malicious IPs and writes them to a
shell script for a human to REVIEW and run. Nothing here executes commands:
auto-blocking straight from log data is how attackers trick tools into
blocking your own admins, your VPN or your upstream DNS.
"""
from __future__ import annotations

import ipaddress
import os
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Dict, Iterable, List, Sequence, Tuple

from .utils import SEVERITY_RANK


@dataclass
class BlockRule:
    ip: str  # always a normalized address from `ipaddress`, never raw log text
    direction: str = "inbound"  # inbound: drop traffic FROM ip, outbound: drop traffic TO ip
    reasons: List[str] = field(default_factory=list)

    @property
    def binary(self) -> str:
        return "ip6tables" if ipaddress.ip_address(self.ip).version == 6 else "iptables"

    @property
    def _spec(self) -> str:
        if self.direction == "outbound":
            return f"OUTPUT -d {self.ip} -j DROP"
        return f"INPUT -s {self.ip} -j DROP"

    def command(self) -> str:
        return f"{self.binary} -A {self._spec}"

    def idempotent_command(self) -> str:
        """Add the rule only if it is not there yet (safe to run the script twice)."""
        return f"{self.binary} -C {self._spec} 2>/dev/null || {self.binary} -A {self._spec}"

    def undo_command(self) -> str:
        return f"{self.binary} -D {self._spec}"


def parse_allowlist(entries: Iterable[str]) -> list:
    """Turn `--allow` values (IPs or CIDRs) into networks. Raises ValueError on bad input."""
    return [ipaddress.ip_network(entry.strip(), strict=False) for entry in entries if entry.strip()]


def plan_blocks(findings: Iterable, allowlist: Sequence = (), min_severity: str = "medium"
                ) -> Tuple[List[BlockRule], List[Tuple[str, str]]]:
    """Decide which IPs to block. Returns (rules, skipped[(ip, reason)])."""
    rules: Dict[Tuple[str, str], BlockRule] = {}
    skipped: Dict[str, str] = {}
    for finding in findings:
        if not finding.block or not finding.ip:
            continue
        if SEVERITY_RANK[finding.severity] < SEVERITY_RANK[min_severity]:
            continue
        try:
            addr = ipaddress.ip_address(finding.ip)
        except ValueError:
            continue  # never put anything that is not a real IP into a shell command
        ip = str(addr)
        if addr.is_loopback or addr.is_unspecified or addr.is_multicast or addr.is_link_local:
            skipped[ip] = "special-purpose address"
            continue
        if any(addr.version == net.version and addr in net for net in allowlist):
            skipped[ip] = "allowlisted"
            continue
        rule = rules.setdefault((ip, finding.block), BlockRule(ip, finding.block))
        if finding.rule not in rule.reasons:
            rule.reasons.append(finding.rule)
    return list(rules.values()), sorted(skipped.items())


def render_script(rules: Sequence[BlockRule]) -> str:
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    lines = [
        "#!/usr/bin/env bash",
        f"# Generated by OwlTriage on {stamp}",
        "# REVIEW EVERY LINE BEFORE RUNNING.   Usage: sudo bash block_ips.sh",
        "# Each rule is added only if it is not already present.",
        "set -euo pipefail",
        "",
    ]
    for rule in rules:
        lines.append(f"# {rule.ip} ({rule.direction}): {', '.join(rule.reasons)}")
        lines.append(rule.idempotent_command())
    lines += ["", f'echo "Applied {len(rules)} block rule(s)."', "", "# ---- Undo (remove a rule) ----"]
    lines += [f"# {rule.undo_command()}" for rule in rules]
    return "\n".join(lines) + "\n"


def write_script(rules: Sequence[BlockRule], path) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_script(rules), encoding="utf-8")
    os.chmod(path, 0o700)  # owner-only: it is run with sudo by whoever generated it
    return path
